export const DEFAULT_RULES = `## Working agreement — non-negotiable

- Read .knowa/rules.md, docs/architecture.md and docs/conventions.md, plus
  the files you are about to change, before your first edit. Say what you read.
- Put new code in the module that already owns the concern, in the patterns
  already there. Get approval before adding a module, dependency or layer.
- Never rewrite, reorganize or regenerate documentation as a side effect of a
  code change. Edit only what the change made wrong, and name every doc file
  you touched in your summary.

## General

- Read .knowa/context.md and docs/architecture.md before making changes.
- Keep changes small and focused; follow existing patterns in the codebase.
- Write or update tests alongside code changes.

## Code Style

- Match the project's existing formatting, naming and idioms.
- Prefer clear, self-explanatory code over comments.

## Safety

- Never commit secrets, API keys or credentials.
- Ask before running destructive commands.
`;

/** Read the canonical rules from .knowa/rules.md (create default if missing). */
export function loadRules(root: string): string {
  const file = path.join(projectDir(root), 'rules.md');
  if (!fs.existsSync(file)) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, DEFAULT_RULES);
  }
  return fs.readFileSync(file, 'utf8');
}

export interface GeneratedFile {
  target: string;
  file: string;
}

/**
 * Mirror files whose content no longer renders from the current
 * `.knowa/rules.md`.
 *
 * The kit tells users to edit `.knowa/rules.md` and re-run, but nothing
 * detected the window in between: a hand-edited rules file whose mirrors still
 * carry the previous text. `knowa sync` uses this to close it.
 *
 * Comparison is on the manifest's cosmetic-insensitive signature, so a repo
 * that runs a markdown formatter over its tool files does not read as
 * permanently stale.
 */
export function staleMirrors(root: string, projectName: string, only?: string[]): string[] {
  const file = path.join(projectDir(root), 'rules.md');
  if (!fs.existsSync(file)) return [];
  const rules = fs.readFileSync(file, 'utf8').trim();
  const stale: string[] = [];
  for (const target of targetsFor(only)) {
    const out = path.join(root, target.file);
    // A mirror this project never had is not stale — it was never claimed.
    if (!fs.existsSync(out)) continue;
    try {
      if (
        signatureOf(fs.readFileSync(out, 'utf8')) !== signatureOf(target.render(rules, projectName))
      )
        stale.push(target.file);
    } catch {
      // Unreadable mirror: leave it alone rather than guess.
    }
  }
  return stale;
}

function targetsFor(only?: string[]): RuleTarget[] {
  return only?.length ? RULE_TARGETS.filter((t) => only.includes(t.id)) : RULE_TARGETS;
}

export function generateRules(root: string, projectName: string, only?: string[]): GeneratedFile[] {
  const rules = loadRules(root);
  const targets = targetsFor(only);
  const written: GeneratedFile[] = [];
  for (const target of targets) {
    const out = path.join(root, target.file);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, target.render(rules.trim(), projectName));
    written.push({ target: target.name, file: target.file });
  }
  return written;
}
