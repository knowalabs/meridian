import fs from 'node:fs';
import path from 'node:path';
import { projectDir } from '../core/paths.js';
import { signatureOf } from '../generate/manifest.js';

/**
 * Rules generator (Phase 2): render one canonical rule set into the
 * instruction-file format of each supported AI tool.
 */

export interface RuleTarget {
  id: string;
  name: string;
  /** Output path relative to project root. */
  file: string;
  render(rules: string, projectName: string): string;
}

const HEADER = `<!-- Generated by knowa generate — edit .knowa/rules.md and re-run to update. -->`;

function standardBody(rules: string, projectName: string, tool: string): string {
  return `${HEADER}

# ${projectName} — Instructions for ${tool}

${rules}
`;
}

